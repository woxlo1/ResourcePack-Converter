export const TRANSLATIONS: Record<Locale, Record<TranslationKey, string>> = { en, ja };

export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'ja';
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const table = TRANSLATIONS[locale] ?? TRANSLATIONS.en;
  const template = table[key] ?? TRANSLATIONS.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

/** Maps an RpcError message key to a translated message. */
export function translateError(locale: Locale, messageKey: string, fallback?: string): string {
  const key = messageKey.startsWith('error.') ? (`errors.${messageKey.slice('error.'.length)}` as TranslationKey) : null;
  if (key && key in TRANSLATIONS.en) return translate(locale, key);
  return fallback ?? translate(locale, 'errors.unknown');
}
